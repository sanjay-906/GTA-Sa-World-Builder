def get_asset(name: str):
    """Return an asset by exact name."""

    return ASSETS.get(
        name.lower().strip()
    )


def search_assets(query: str):
    """Search asset names, categories and descriptions."""

    query = query.lower().strip()

    results = []

    for name, asset in ASSETS.items():

        searchable = " ".join(
            [
                name,
                asset.get("category", ""),
                asset.get("description", ""),
            ]
        ).lower()

        if query in searchable:

            results.append(
                {
                    "name": name,
                    **asset,
                }
            )

    return results


def list_assets():
    """Return all registered assets."""

    return [
        {
            "name": name,
            **asset,
        }
        for name, asset in ASSETS.items()
    ]
